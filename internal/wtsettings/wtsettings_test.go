package wtsettings

import (
	"encoding/json"
	"strings"
	"testing"
)

// A settings.json as Windows Terminal writes it: comments, a trailing comma, dynamic profiles.
const sample = `// This file was initially generated by Windows Terminal 1.24
{
    "$help": "https://aka.ms/terminal-documentation",
    "defaultProfile": "{04d0c07a-b717-5790-a033-fbd379a82afb}", // Ubuntu
    "profiles": {
        "defaults": { "font": { "face": "Cascadia Mono" } },
        "list": [
            { "guid": "{61c54bbd-c2c6-5271-96e7-009a87ff44bf}", "name": "Windows PowerShell", "hidden": false },
            /* the dynamic PowerShell 7 profile */
            {
                "guid": "{574e775e-4f2a-5b96-ac1e-a2962a402336}",
                "hidden": false,
                "name": "PowerShell",
                "source": "Windows.Terminal.PowershellCore"
            },
            { "guid": "{04d0c07a-b717-5790-a033-fbd379a82afb}", "name": "Ubuntu", "source": "Windows.Terminal.Wsl", },
        ]
    }
}
`

func TestReadsTheDefaultAndPowerShell7Profile(t *testing.T) {
	st, err := Read([]byte(sample), PowerShellCore)
	if err != nil {
		t.Fatal(err)
	}
	if st.Default != "{04d0c07a-b717-5790-a033-fbd379a82afb}" || st.Profile != "{574e775e-4f2a-5b96-ac1e-a2962a402336}" {
		t.Errorf("%+v", st)
	}
	if st.IsDefault() {
		t.Error("PowerShell 7 is not the default here")
	}
}

func TestAHiddenOrMissingProfileIsNotFound(t *testing.T) {
	hidden := strings.Replace(sample, `"hidden": false,
                "name": "PowerShell"`, `"hidden": true,
                "name": "PowerShell"`, 1)
	for name, text := range map[string]string{"hidden": hidden, "missing": strings.Replace(sample, "Windows.Terminal.PowershellCore", "x", 1)} {
		st, err := Read([]byte(text), PowerShellCore)
		if err != nil || st.Profile != "" {
			t.Errorf("%s: %+v %v", name, st, err)
		}
	}
}

// SetDefault changes only the defaultProfile value: every other byte (comments too) stays.
func TestSetDefaultChangesOnlyTheValue(t *testing.T) {
	out, err := SetDefault([]byte(sample), "{574e775e-4f2a-5b96-ac1e-a2962a402336}")
	if err != nil {
		t.Fatal(err)
	}
	want := strings.Replace(sample, `"defaultProfile": "{04d0c07a-b717-5790-a033-fbd379a82afb}"`, `"defaultProfile": "{574e775e-4f2a-5b96-ac1e-a2962a402336}"`, 1)
	if string(out) != want {
		t.Errorf("got\n%s", out)
	}
	st, _ := Read(out, PowerShellCore)
	if !st.IsDefault() {
		t.Error("not the default after SetDefault")
	}
}

// A defaultProfile key inside a profile (not the top level) is never the one changed; a file
// without a top-level one, or that is not JSON, is refused.
func TestSetDefaultRefusesWhatItCannotChangeSafely(t *testing.T) {
	if _, err := SetDefault([]byte(`{"profiles": {"list": [{"defaultProfile": "x"}]}}`), "{g}"); err == nil {
		t.Error("changed a nested key")
	}
	if _, err := SetDefault([]byte(`{ not json`), "{g}"); err == nil {
		t.Error("accepted broken JSON")
	}
	if _, err := SetDefault([]byte(sample), `{"bad`); err == nil {
		t.Error("accepted a guid with a quote")
	}
}

func TestStripMakesJSONAndKeepsStrings(t *testing.T) {
	got := Strip([]byte(`{"a": "http://x//y /* z */", /* c */ "b": [1,], } // end`))
	if !json.Valid(got) || !strings.Contains(string(got), `"http://x//y /* z */"`) {
		t.Errorf("%q", got)
	}
}
